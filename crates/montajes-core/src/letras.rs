//! Letra de trazos para los rótulos de las planchas.
//!
//! Los rótulos se dibujan con líneas (no con una fuente): así no hace falta
//! incrustar fuentes y el PDF sigue siendo PDF/X. Cada letra ocupa una
//! cuadrícula de 4 × 6 unidades (mayúsculas); las minúsculas se escriben en
//! mayúscula y las tildes se quitan.

/// Ancho de avance de una letra, en unidades (4 de letra + 2 de espacio).
const AVANCE: f64 = 6.0;
const AVANCE_ESPACIO: f64 = 4.0;

type Trazo = &'static [(f64, f64)];

const ARO: Trazo = &[(1., 0.), (0., 1.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 1.), (3., 0.), (1., 0.)];
const O: &[Trazo] = &[ARO];
const P: &[(f64, f64)] = &[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)];

fn trazos(c: char) -> Option<&'static [Trazo]> {
    Some(match c {
        'A' => &[&[(0., 0.), (0., 4.), (2., 6.), (4., 4.), (4., 0.)], &[(0., 3.), (4., 3.)]],
        'B' => &[
            &[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)],
            &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)],
        ],
        'C' => &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (3., 0.), (4., 1.)]],
        'D' => &[&[(0., 0.), (0., 6.), (2., 6.), (4., 4.), (4., 2.), (2., 0.), (0., 0.)]],
        'E' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)], &[(0., 3.), (3., 3.)]],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 3.), (2., 3.)]],
        'H' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (4., 6.)], &[(0., 3.), (4., 3.)]],
        'I' => &[&[(1., 6.), (3., 6.)], &[(2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        'J' => &[&[(4., 6.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 2.)], &[(1., 3.), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'O' => O,
        'P' => &[P],
        'Q' => &[ARO, &[(2., 2.), (4., 0.)]],
        'R' => &[P, &[(2., 3.), (4., 0.)]],
        'S' => &[&[
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 4.),
            (1., 3.),
            (3., 3.),
            (4., 2.),
            (4., 1.),
            (3., 0.),
            (1., 0.),
            (0., 1.),
        ]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 4.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        '0' => &[ARO, &[(0., 1.), (4., 5.)]],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[(0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (0., 0.), (4., 0.)]],
        '3' => &[
            &[
                (0., 5.),
                (1., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (4., 2.),
                (4., 1.),
                (3., 0.),
                (1., 0.),
                (0., 1.),
            ],
            &[(1., 3.), (3., 3.)],
        ],
        '4' => &[&[(3., 0.), (3., 6.), (0., 2.), (4., 2.)]],
        '5' => &[&[(4., 6.), (0., 6.), (0., 3.), (3., 3.), (4., 2.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        '6' => &[&[
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 2.),
            (3., 3.),
            (0., 3.),
        ]],
        '7' => &[&[(0., 6.), (4., 6.), (1., 0.)]],
        '8' => &[&[
            (1., 3.),
            (0., 4.),
            (0., 5.),
            (1., 6.),
            (3., 6.),
            (4., 5.),
            (4., 4.),
            (3., 3.),
            (1., 3.),
            (0., 2.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 2.),
            (3., 3.),
        ]],
        '9' => &[&[
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 4.),
            (1., 3.),
            (4., 3.),
        ]],
        '.' => &[&[(2., 0.), (2., 0.5)]],
        ',' => &[&[(2., 0.6), (1.5, -0.6)]],
        ':' => &[&[(2., 1.), (2., 1.5)], &[(2., 4.), (2., 4.5)]],
        '·' => &[&[(2., 2.8), (2., 3.3)]],
        '-' | '–' | '—' => &[&[(1., 3.), (3., 3.)]],
        '_' => &[&[(0., 0.), (4., 0.)]],
        '/' => &[&[(0., 0.), (4., 6.)]],
        '+' => &[&[(2., 1.), (2., 5.)], &[(0., 3.), (4., 3.)]],
        '×' => &[&[(0.5, 1.), (3.5, 5.)], &[(0.5, 5.), (3.5, 1.)]],
        '(' => &[&[(3., 6.), (2., 5.), (2., 1.), (3., 0.)]],
        ')' => &[&[(1., 6.), (2., 5.), (2., 1.), (1., 0.)]],
        '#' => &[&[(1., 0.), (1.5, 6.)], &[(2.5, 0.), (3., 6.)], &[(0., 2.), (4., 2.)], &[(0., 4.), (4., 4.)]],
        '%' => &[&[(0., 0.), (4., 6.)], &[(0., 5.), (0.5, 5.5)], &[(3.5, 0.5), (4., 1.)]],
        '&' => &[&[(4., 0.), (1., 4.), (1., 5.), (2., 6.), (3., 5.), (0., 2.), (0., 1.), (1., 0.), (3., 0.), (4., 2.)]],
        '\'' => &[&[(2., 6.), (2., 4.5)]],
        _ => return None,
    })
}

/// La letra que se dibuja: mayúscula y sin tilde.
fn normalizar(c: char) -> char {
    let c = c.to_uppercase().next().unwrap_or(c);
    match c {
        'Á' | 'À' | 'Ä' | 'Â' | 'Ã' => 'A',
        'É' | 'È' | 'Ë' | 'Ê' => 'E',
        'Í' | 'Ì' | 'Ï' | 'Î' => 'I',
        'Ó' | 'Ò' | 'Ö' | 'Ô' | 'Õ' => 'O',
        'Ú' | 'Ù' | 'Ü' | 'Û' => 'U',
        'Ñ' => 'N',
        'Ç' => 'C',
        otra => otra,
    }
}

/// Largo (mm) de un texto escrito con letras de `alto` mm.
pub fn largo(texto: &str, alto: f64) -> f64 {
    let u = alto / 6.0;
    let mut total = 0.0;
    for c in texto.chars() {
        let c = normalizar(c);
        total += if trazos(c).is_some() { AVANCE } else { AVANCE_ESPACIO };
    }
    (total - 2.0).max(0.0) * u
}

/// Recorta un texto para que quepa en `maximo` mm (con «…» como «...»).
pub fn ajustar(texto: &str, alto: f64, maximo: f64) -> String {
    if largo(texto, alto) <= maximo {
        return texto.to_string();
    }
    let mut s: String = texto.to_string();
    while !s.is_empty() && largo(&format!("{s}..."), alto) > maximo {
        s.pop();
    }
    if s.is_empty() { String::new() } else { format!("{}...", s.trim_end()) }
}

/// Trazos de un texto en unidades de letra (alto 6), desde (0, 0) hacia la
/// derecha: devuelve los segmentos como listas de puntos y el avance total.
pub fn segmentos(texto: &str) -> (Vec<Vec<(f64, f64)>>, f64) {
    let mut x = 0.0;
    let mut salida = Vec::new();
    for c in texto.chars() {
        let c = normalizar(c);
        match trazos(c) {
            Some(lista) => {
                for t in lista {
                    salida.push(t.iter().map(|(a, b)| (a + x, *b)).collect());
                }
                x += AVANCE;
            }
            None => x += AVANCE_ESPACIO,
        }
    }
    (salida, x)
}

#[cfg(test)]
mod pruebas {
    use super::*;

    #[test]
    fn largo_y_ajuste() {
        // «AB» = 6 + 6 − 2 = 10 unidades; a 3 mm de alto, 5 mm.
        assert!((largo("AB", 3.0) - 5.0).abs() < 1e-9);
        assert_eq!(largo("ñá", 6.0), largo("NA", 6.0));
        let s = ajustar("VOLANTES MUY LARGOS PARA EL ROTULO", 3.0, 20.0);
        assert!(s.ends_with("...") && largo(&s, 3.0) <= 20.0);
        let (seg, avance) = segmentos("T 1");
        assert_eq!(seg.len(), 4);
        assert_eq!(avance, 16.0);
    }
}
